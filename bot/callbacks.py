"""
Схемы callback_data (Промпт 6, п.7): pydantic-фабрики aiogram вместо ручных
строк вида "rec:done:42".

Почему это не педантизм: в callback_data всего 64 байта, а состояние экрана
здесь не хранится на сервере — оно целиком лежит в самой кнопке (откуда
пришли, какая страница, какие фильтры). Собирать и разбирать такую строку
руками — это ровно тот код, где опечатка не ломает импорт, а тихо ведёт
пользователя не туда. Фабрика и собирает, и валидирует типы за нас.

Коды намеренно однобуквенные — по той же причине лимита в 64 байта.
Старые кнопки (v:y:/v:c:/c:p: из Промптов 3-4) остаются как есть: у них
свои префиксы, они не пересекаются с этими.
"""

from __future__ import annotations

from aiogram.filters.callback_data import CallbackData

# src — откуда открыт экран, чтобы "Назад" вернул ровно туда же:
#   "l" — /list, "t" — /today, "w" — клавиатура под обложкой недели.
SRC_LIST = "l"
SRC_TODAY = "t"
SRC_WEEK = "w"


class ListCB(CallbackData, prefix="ls"):
    """Экран списка: страницы и переключение фильтров."""

    act: str  # "p" — страница, "ft" — сменить тип, "fs" — сменить статус, "n" — ничего
    src: str
    page: int
    ftype: str
    fstat: str


class RecordCB(CallbackData, prefix="rc"):
    """Карточка записи и её действия. Фильтры едут с собой ради кнопки «Назад»."""

    act: str  # "o" открыть, "d" готово, "pm" меню переноса, "p" перенести, "da" спросить, "dy" удалить, "b" назад
    id: int
    src: str
    page: int
    ftype: str
    fstat: str
    arg: str = ""  # пресет переноса: "t" сегодня, "m" завтра, "w" +неделя


class SettingsCB(CallbackData, prefix="st"):
    """Экран настроек. Пока единственная настройка — час вечернего чек-ина."""

    act: str  # "hm" — меню выбора часа, "h" — выбран час, "b" — назад в настройки
    val: int = 0
