"""
Кто прямо сейчас должен получить вечерний чек-ин — по локальному времени
пользователя, а не по времени сервера.

Один и тот же момент в UTC — это разный час у пользователей в разных поясах.
Планировщик (bot/scheduler.py) будит эту проверку раз в час, но отправлять
чек-ин нужно только тем, у кого именно сейчас, по ИХ часам, наступило 20:00 —
остальные ждут своего часа.
"""

from __future__ import annotations

import datetime as dt

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from db.models import User
from services import timeframe

# Дефолт: 20:00. С Промпта 6 это уже не константа поведения, а лишь значение
# по умолчанию — час хранится в users.checkin_hour и меняется через /settings.
# Здесь оно остаётся как единственное место, где записан "дефолт продукта".
CHECKIN_HOUR = 20


def is_checkin_hour(timezone: str, at_utc: dt.datetime, hour: int = CHECKIN_HOUR) -> bool:
    """
    Наступил ли сейчас (at_utc) час вечернего чек-ина в поясе ``timezone``.

    Сравнение по часу, а не по точному "20:00:00", — потому что вызывающий
    код (services/checkin.due_users) проверяет это раз в час, а не раз в
    секунду: если сейчас где-то в интервале [20:00, 21:00) по местному
    времени, значит это тот самый часовой прогон, который должен дойти именно
    до этого пользователя. Смещения часовых поясов бывают не кратны целому
    часу (Индия +5:30, Непал +5:45), но сам локальный час всё равно проходит
    все 24 значения ровно по одному разу за 24 часовых прогона — так что
    двойной отправки или пропуска из-за дробного смещения не происходит.
    """
    return timeframe.to_local(at_utc, timezone).hour == hour


async def due_users(session: AsyncSession, at_utc: dt.datetime) -> list[User]:
    """
    Пользователи, которым нужно прислать чек-ин прямо сейчас.

    Перебирает всех пользователей и фильтрует в Python, а не в SQL: часовой
    пояс — это IANA-строка с DST-переходами, вычислять "текущий локальный час"
    прямо в запросе ощутимо сложнее, чем в zoneinfo, а с ростом на несколько
    сотен пользователей это не узкое место. Если аудитория вырастет на
    порядки — первое место, которое стоит оптимизировать (например, хранить
    смещение отдельной колонкой и фильтровать в SQL).
    """
    users = list((await session.scalars(select(User))).all())
    return [u for u in users if is_checkin_hour(u.timezone, at_utc, u.checkin_hour)]
